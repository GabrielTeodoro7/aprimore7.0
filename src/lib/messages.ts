export const showAppMessage = (key: string, type: "success" | "error" | "info" | "warning" = "info") => {
  // Busca em todas as categorias se a chave existir
  for (const cat in AppMessages) {
    const category = (AppMessages as any)[cat];
    if (category[key]) {
      toast[type === "info" && cat === "SUCCESS" ? "success" : type === "info" && cat === "ERROR" ? "error" : type](category[key]);
      return;
    }
  }
  toast[type](key);
};
